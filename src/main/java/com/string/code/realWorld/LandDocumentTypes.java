public class LandDocumentTypes {

    public static void main(String[] args) {

        System.out.println("Land Document Types and Their Explanation:");
        System.out.println("-------------------------------------------");

        System.out.println("1. Pani (RTC)");
        System.out.println("   - Record of Rights, Tenancy and Crops.");
        System.out.println("   - Contains details of land owner, area, and crops grown.\n");

        System.out.println("2. Mutation");
        System.out.println("   - Process of transferring land ownership.");
        System.out.println("   - Updated in government records after sale or inheritance.\n");

        System.out.println("3. Khata");
        System.out.println("   - Legal document for property tax purposes.");
        System.out.println("   - Confirms property is recorded in local municipal records.\n");

        System.out.println("4. Sale Deed");
        System.out.println("   - Legal document proving sale and transfer of property.");
        System.out.println("   - Registered at the sub-registrar office.\n");

        System.out.println("5. Encumbrance Certificate (EC)");
        System.out.println("   - Shows whether the property has any legal or financial liabilities.");
        System.out.println("   - Required for property transactions and loans.\n");

        System.out.println("6. Patta");
        System.out.println("   - Legal ownership document issued by the government.");
        System.out.println("   - Contains survey number and land details.\n");

        System.out.println("7. Chitta");
        System.out.println("   - Revenue document showing land classification.");
        System.out.println("   - Indicates whether land is agricultural or non-agricultural.\n");
    }
}