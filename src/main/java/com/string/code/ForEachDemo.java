public class ForEachDemo {
    public static void main(String[] args) {

        // Array of integers
        int[] numbers = {10, 20, 30, 40, 50};

        // Using for-each loop
        System.out.println("Elements in the array:");
        for (int num : numbers) {
            System.out.println(num);
        }
    }
}
